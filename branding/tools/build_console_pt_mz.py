#!/usr/bin/env python3
"""
Builds console/translations/pt-mz.yaml (committed) with every en-us key present:

    value = hand override  ->  pt-br converted to pt-MZ  ->  en-us fallback

    python branding/tools/build_console_pt_mz.py

Requires PyYAML and Node (uses console/scripts/transweb/make-pt-mz.js for the pt-BR -> pt-MZ
conversion so the console and the extension engines use the same rules).
Extension engines get their pt-mz.yaml at Docker build time (see console/Dockerfile).
"""
import json, subprocess, sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONSOLE = ROOT / "console"
T = CONSOLE / "translations"
SCRIPT = CONSOLE / "scripts/transweb/make-pt-mz.js"
OVERRIDES = CONSOLE / "scripts/transweb/pt-mz.overrides.yaml"


def flat(d, p=""):
    out = {}
    for k, v in (d or {}).items():
        kk = f"{p}.{k}" if p else str(k)
        out.update(flat(v, kk) if isinstance(v, dict) else {kk: v})
    return out


def unflat(pairs):
    root = {}
    for key, value in pairs:
        node = root
        *parents, leaf = key.split(".")
        for part in parents:
            node = node.setdefault(part, {})
        node[leaf] = value
    return root


def convert_br(text: str) -> str:
    js = f"process.stdout.write(require({json.dumps(str(SCRIPT))}).convert(require('fs').readFileSync(0,'utf8')))"
    return subprocess.run(["node", "-e", js], input=text, capture_output=True, text=True, encoding="utf-8", check=True).stdout


def main():
    en = flat(yaml.safe_load((T / "en-us.yaml").read_text(encoding="utf-8")))
    br = flat(yaml.safe_load(convert_br((T / "pt-br.yaml").read_text(encoding="utf-8"))))
    ov = {}
    for line in OVERRIDES.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#") and ": " in line:
            k, v = line.split(": ", 1)
            ov[k.strip()] = v
    unknown = sorted(set(ov) - set(en))
    if unknown:
        sys.exit(f"Overrides reference keys that are not in en-us.yaml: {unknown}")

    pairs, fallback = [], []
    for key, en_value in en.items():
        if key in ov:
            value = ov[key]
        elif key in br and not (br[key] == en_value and isinstance(en_value, str) and len(en_value) > 3 and any(c.isalpha() for c in en_value)):
            value = br[key]
        else:
            value = en_value
            fallback.append(key)
        pairs.append((key, value))

    header = "# Português (Moçambique). Generated by branding/tools/build_console_pt_mz.py — edit\n# console/scripts/transweb/pt-mz.overrides.yaml and re-run instead of editing by hand.\n"
    body = yaml.safe_dump(unflat(pairs), allow_unicode=True, sort_keys=False, width=1000, default_flow_style=False)
    (T / "pt-mz.yaml").write_text(header + body, encoding="utf-8", newline="\n")
    print(f"pt-mz.yaml: {len(pairs)} keys, {len(ov)} overrides, {len(fallback)} still English")
    for k in fallback:
        print("  EN:", k)


if __name__ == "__main__":
    main()
